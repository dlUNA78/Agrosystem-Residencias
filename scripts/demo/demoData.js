const resolveDemoCredential = (env, envKey, roleTag) => {
  const fromEnv = String(env?.[envKey] || '').trim();
  const credential = fromEnv || ['AgroDemo', roleTag, '2026'].join('');
  const check = validatePasswordPolicy(credential);
  if (!check.valid) {
    throw new Error(
      `La credencial demo para ${roleTag} no cumple validatePasswordPolicy: ${check.errors.join(' ')}`,
    );
  }
  return credential;
};

